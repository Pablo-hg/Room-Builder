import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('compara variantes, deshace cambios de activa y guarda y recarga ambas', async ({ page }) => {
  await page.goto('/')
  const variants = page.getByRole('region', { name: 'Comparar distribuciones' })
  await page.getByRole('button', { name: /Sillón.*Añadir/ }).click()
  await variants.getByRole('button', { name: 'Duplicar como alternativa' }).click()
  await expect(variants.getByRole('button', { name: 'Alternativa A', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(variants.getByRole('button', { name: 'Duplicar como alternativa' })).toBeDisabled()
  await page.getByRole('button', { name: /Sofá.*Añadir/ }).click()
  const sofas = page.locator('.element-row').filter({ hasText: 'Sofá' })
  await expect(sofas).toHaveCount(1)
  await page.getByRole('button', { name: 'Plano', exact: true }).click()
  await variants.getByRole('button', { name: 'Original', exact: true }).click()
  await expect(sofas).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Plano', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Deshacer el último cambio', exact: true }).click()
  await expect(sofas).toHaveCount(1)
  await expect(variants.getByRole('button', { name: 'Alternativa A', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Guardar como', exact: true }).click()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('room-builder:v0.1:designs')!))
  expect(saved[0].data.version).toBe(5)
  expect(saved[0].data.layouts.map((layout: { furniture: unknown[] }) => layout.furniture.length)).toEqual([1, 2])
  expect(saved[0].data.furniture).toEqual(saved[0].data.layouts[1].furniture)
  await page.reload()
  await page.getByRole('button', { name: 'Seleccionar diseño guardado' }).click()
  await expect(page.getByText('2 variantes', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Diseño 1', exact: true }).click()
  await expect(variants.getByRole('button', { name: 'Alternativa A', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(sofas).toHaveCount(1)
  await variants.getByRole('button', { name: 'Original', exact: true }).click()
  await expect(sofas).toHaveCount(0)
})

test('renombra con teclado y confirma o cancela la eliminación de alternativa', async ({ page }) => {
  await page.goto('/')
  const variants = page.getByRole('region', { name: 'Comparar distribuciones' })
  await variants.getByRole('button', { name: 'Duplicar como alternativa' }).click()
  await variants.getByRole('button', { name: 'Renombrar variante' }).click()
  const name = variants.getByRole('textbox', { name: 'Nombre de la variante' })
  await expect(name).toBeFocused()
  await name.fill('Más espacio')
  await name.press('Enter')
  await expect(variants.getByRole('button', { name: 'Más espacio', exact: true })).toHaveAttribute('aria-pressed', 'true')
  page.once('dialog', (dialog) => dialog.dismiss())
  await variants.getByRole('button', { name: 'Eliminar alternativa' }).click()
  await expect(variants.getByRole('button', { name: 'Más espacio', exact: true })).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  await variants.getByRole('button', { name: 'Eliminar alternativa' }).click()
  await expect(variants.getByRole('button', { name: 'Original', exact: true })).toBeFocused()
  await expect(variants.getByRole('button', { name: 'Eliminar alternativa' })).toBeDisabled()
  await page.getByRole('button', { name: 'Deshacer el último cambio', exact: true }).click()
  await expect(variants.getByRole('button', { name: 'Más espacio', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('rechaza un v5 con espejo discrepante sin modificar almacenamiento', async ({ page }) => {
  const data = JSON.parse(readFileSync(new URL('./fixtures/layout-variants/valid-v5.json', import.meta.url), 'utf8'))
  data.furniture[0].x += 1
  const saved = [{ id: 'broken', name: 'Inconsistente', savedAt: '2026-11-03T10:00:00.000Z', data }]
  await page.addInitScript((designs) => localStorage.setItem('room-builder:v0.1:designs', JSON.stringify(designs)), saved)
  await page.goto('/')
  await expect(page.locator('.toast')).toContainText('no coincide')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('room-builder:v0.1:designs')!))).toEqual(saved)
})

test('selector accesible sin desbordamiento en escritorio y móvil', async ({ page }) => {
  await page.goto('/')
  const variants = page.getByRole('region', { name: 'Comparar distribuciones' })
  await variants.getByRole('button', { name: 'Duplicar como alternativa' }).click()
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    await variants.scrollIntoViewIfNeeded()
    await expect(variants.getByRole('button', { name: 'Original', exact: true })).toBeVisible()
    await expect(variants.getByRole('button', { name: 'Alternativa A', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: '/tmp/room-builder-r51-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 900 })
  await variants.scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/room-builder-r51-mobile.png', fullPage: true })
})
