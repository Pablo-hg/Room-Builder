import { expect, test } from '@playwright/test'

test('soltar un objeto sobre una fila exterior lo saca de la carpeta', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1200 })
  await page.goto('/')
  const catalog = page.getByRole('complementary', { name: 'Catálogo de objetos' })
  await catalog.getByRole('button', { name: 'Crear carpeta de elementos' }).click()
  await page.getByRole('button', { name: 'Ventana ＋ Añadir', exact: true }).click()
  await catalog.getByRole('button', { name: 'Minimizar catálogo completo' }).click()
  const window = catalog.locator('.element-row').filter({ hasText: 'Ventana 2' })
  const folder = catalog.locator('.element-folder').filter({ has: page.getByRole('button', { name: 'Carpeta Carpeta 1', exact: true }) }).first()
  const door = catalog.locator('.element-row').filter({ hasText: 'Puerta' })
  await window.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Mover a', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Carpeta 1', exact: true }).click()
  await expect(folder.locator('.element-row').filter({ hasText: 'Ventana 2' })).toBeVisible()
  await window.dragTo(door, { sourcePosition: { x: 12, y: 12 }, targetPosition: { x: 12, y: 4 } })
  await expect(folder.locator('.element-row').filter({ hasText: 'Ventana 2' })).toHaveCount(0)
  await expect.poll(async () => (await window.boundingBox())!.y < (await door.boundingBox())!.y).toBe(true)
})

test('el menú y el arrastre actúan sobre toda la selección y permiten agrupar', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1200 })
  await page.goto('/')
  const catalog = page.getByRole('complementary', { name: 'Catálogo de objetos' })
  await page.getByRole('button', { name: 'Silla ＋ Añadir', exact: true }).click()
  await page.getByRole('button', { name: 'Mesa ＋ Añadir', exact: true }).click()
  await catalog.getByRole('button', { name: 'Crear carpeta de elementos' }).click()
  await catalog.getByRole('button', { name: 'Minimizar catálogo completo' }).click()
  const row = (name: string) => catalog.locator('.element-row').filter({ has: page.locator('.element-select strong', { hasText: name }) })
  const chair = row('Silla')
  const table = row('Mesa')
  await chair.locator('.element-select').click()
  await table.locator('.element-select').click({ modifiers: ['Control'] })
  await chair.click({ button: 'right' })
  const menu = page.getByRole('menu', { name: 'Acciones de 2 elementos' })
  await expect(menu.getByRole('menuitem', { name: 'Renombrar' })).toHaveCount(0)
  await expect(menu.getByRole('menuitem', { name: 'Agrupar' })).toBeVisible()
  await menu.getByRole('menuitem', { name: 'Mover a', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Carpeta 1', exact: true }).click()
  const folder = catalog.locator('.element-folder').filter({ has: page.getByRole('button', { name: 'Carpeta Carpeta 1', exact: true }) }).first()
  await expect(folder.locator('.element-row').filter({ hasText: 'Silla' })).toBeVisible()
  await expect(folder.locator('.element-row').filter({ hasText: 'Mesa' })).toBeVisible()
  await chair.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Agrupar', exact: true }).click()
  const group = folder.locator('.element-folder').filter({ has: page.getByRole('button', { name: 'Carpeta Carpeta 2', exact: true }) })
  await expect(group.locator('.element-row').filter({ hasText: 'Silla' })).toBeVisible()
  await expect(group.locator('.element-row').filter({ hasText: 'Mesa' })).toBeVisible()
  await page.getByRole('button', { name: 'Deshacer el último cambio' }).click()
  await chair.locator('.element-select').click()
  await table.locator('.element-select').click({ modifiers: ['Control'] })
  const door = row('Puerta')
  await chair.scrollIntoViewIfNeeded()
  await chair.dragTo(door, { force: true, timeout: 12_000, sourcePosition: { x: 10, y: 10 }, targetPosition: { x: 10, y: 5 } })
  await expect(folder.locator('.element-row').filter({ hasText: 'Silla' })).toHaveCount(0)
  await expect(folder.locator('.element-row').filter({ hasText: 'Mesa' })).toHaveCount(0)
  await expect.poll(async () => (await chair.boundingBox())!.y < (await door.boundingBox())!.y).toBe(true)
})

test('duplica y borra toda la selección y deshace cada operación', async ({ page }) => {
  await page.goto('/')
  const catalog = page.getByRole('complementary', { name: 'Catálogo de objetos' })
  await page.getByRole('button', { name: 'Silla ＋ Añadir', exact: true }).click()
  await page.getByRole('button', { name: 'Mesa ＋ Añadir', exact: true }).click()
  const row = (name: string) => catalog.locator('.element-row').filter({ has: page.locator('.element-select strong', { hasText: name }) })
  await row('Silla').locator('.element-select').click()
  await row('Mesa').locator('.element-select').click({ modifiers: ['Control'] })
  await row('Mesa').click({ button: 'right' })
  const menu = page.getByRole('menu', { name: 'Acciones de 2 elementos' })
  await expect(menu.getByRole('menuitem', { name: /Duplicar/ })).toBeEnabled()
  await menu.getByRole('menuitem', { name: /Duplicar/ }).click()
  await expect(row('Silla')).toHaveCount(2)
  await expect(row('Mesa')).toHaveCount(2)
  await expect(page.getByRole('heading', { name: '2 elementos seleccionados' })).toBeVisible()
  await page.keyboard.press('Delete')
  await expect(row('Silla')).toHaveCount(1)
  await expect(row('Mesa')).toHaveCount(1)
  await page.getByRole('button', { name: 'Deshacer el último cambio' }).click()
  await expect(row('Silla')).toHaveCount(2)
  await expect(row('Mesa')).toHaveCount(2)
  await page.getByRole('button', { name: 'Deshacer el último cambio' }).click()
  await expect(row('Silla')).toHaveCount(1)
  await expect(row('Mesa')).toHaveCount(1)
})

test('ofrece desagrupar al seleccionar una carpeta y conserva los objetos', async ({ page }) => {
  await page.goto('/')
  const catalog = page.getByRole('complementary', { name: 'Catálogo de objetos' })
  await page.getByRole('button', { name: 'Silla ＋ Añadir', exact: true }).click()
  await catalog.getByRole('button', { name: 'Crear carpeta de elementos' }).click()
  const row = catalog.locator('.element-row').filter({ hasText: 'Silla' })
  await row.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Mover a', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Carpeta 1', exact: true }).click()
  const folder = catalog.getByRole('button', { name: 'Carpeta Carpeta 1', exact: true })
  await folder.click()
  const inspector = page.getByRole('region', { name: 'Inspector de la carpeta' })
  await expect(inspector.getByRole('button', { name: 'Desagrupar' })).toBeVisible()
  await inspector.getByRole('button', { name: 'Desagrupar' }).click()
  await expect(folder).toHaveCount(0)
  await expect(row).toBeVisible()
  await page.getByRole('button', { name: 'Deshacer el último cambio' }).click()
  await expect(folder).toBeVisible()
  await folder.click()
  await page.keyboard.press('Control+Shift+g')
  await expect(folder).toHaveCount(0)
  await expect(row).toBeVisible()
})
