import { expect, test } from '@playwright/test'

test('edita una apertura respetando pared, giro y límites', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Ventana 1 Apertura/ }).click()
  const inspector = page.getByRole('complementary', { name: 'Inspector y configuración detallada' })
  await expect(inspector.getByRole('heading', { name: 'Ventana' })).toBeVisible()
  const offset = inspector.getByLabel('Posición X', { exact: true })
  const initialOffset = await offset.inputValue()
  await offset.focus()
  await offset.press('ArrowRight')
  await expect(offset).not.toHaveValue(initialOffset)
  const movedOffset = Number(await offset.inputValue())
  await offset.press('End')
  expect(Number(await offset.inputValue())).toBeLessThanOrEqual(Number(await offset.getAttribute('max')))
  for (let step = 0; step < 4; step += 1) await offset.press('ArrowLeft')
  await inspector.getByRole('textbox', { name: 'Introducir X en metros' }).fill('0')
  await inspector.getByRole('textbox', { name: 'Introducir X en metros' }).press('Enter')
  const rotation = inspector.getByRole('spinbutton', { name: 'Giro' })
  await rotation.fill('30')
  await expect(rotation).toHaveValue('30')
  await inspector.getByRole('group', { name: 'Pared', exact: true }).getByRole('button', { name: 'B', exact: true }).click()
  await expect(inspector.getByRole('group', { name: 'Pared', exact: true }).getByRole('button', { name: 'B', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Deshacer el último cambio' }).click()
  await expect(inspector.getByText('Selecciona un mueble, la puerta o una ventana', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: /Ventana 1 Apertura/ }).click()
  await expect(inspector.getByRole('group', { name: 'Pared', exact: true }).getByRole('button', { name: 'A', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(movedOffset).toBeGreaterThan(Number(initialOffset))
})

test('arrastra una ventana en la escena frontal', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const orientation = page.getByRole('button', { name: 'Ver en isométrica las paredes A y B', includeHidden: true })
  await orientation.focus()
  await orientation.press('Enter')
  await page.getByRole('button', { name: 'Frontal', exact: true }).click()
  await expect(page.locator('.visible-walls-badge')).toContainText('Frente: A')
  const bounds = await page.locator('.scene-panel canvas').first().boundingBox()
  if (!bounds) throw new Error('No se pudo localizar el canvas')
  const x = bounds.x + bounds.width * 0.5
  const y = bounds.y + bounds.height * 0.475
  await page.mouse.click(x, y)
  const inspector = page.getByRole('complementary', { name: 'Inspector y configuración detallada' })
  await expect(inspector.getByRole('heading', { name: 'Ventana', exact: true })).toBeVisible()
  const offset = inspector.getByLabel('Posición X', { exact: true })
  const previous = await offset.inputValue()
  await page.mouse.move(x + 35, y)
  await page.mouse.down()
  await page.waitForTimeout(300)
  await page.mouse.move(x + 125, y, { steps: 8 })
  await page.mouse.up()
  await expect(offset).not.toHaveValue(previous)
})

