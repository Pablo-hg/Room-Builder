import { expect, test, type Page } from '@playwright/test'

async function expandCatalogCategory(page: Page, category: string) {
  const toggle = page.getByRole('button', { name: category, exact: true })
  if (await toggle.getAttribute('aria-expanded') === 'false') await toggle.click()
}
import { readFile } from 'node:fs/promises'
import { expandAllCatalogCategories } from './helpers/catalog'

test('edita medidas, guarda y recupera ventanas y mobiliario', async ({ page }) => {
  await page.goto('/')
  await expandAllCatalogCategories(page)
  await expandCatalogCategory(page, 'Aperturas')
  await expandCatalogCategory(page, 'Asientos')
  await page.getByRole('button', { name: 'Silla ＋ Añadir', exact: true }).click()
  const width = page.getByRole('textbox', { name: 'Introducir anchura del objeto en metros' })
  await width.fill('115 cm')
  await width.press('Enter')
  await expect(width).toHaveValue('1.15')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await page.getByRole('button', { name: 'Ventana ＋ Añadir', exact: true }).click()
  const windowWidth = page.getByRole('textbox', { name: 'Introducir anchura del objeto en metros' })
  await windowWidth.fill('1,17')
  await windowWidth.press('Enter')
  await expect(windowWidth).toHaveValue('1.17')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Seleccionar diseño guardado' }).click()
  await page.getByRole('button', { name: 'Diseño 1', exact: true }).click()
  const data = await page.evaluate(() => JSON.parse(localStorage.getItem('room-builder:v0.1:designs')!)[0].data)
  expect(data.furniture[0].width).toBe(1.15)
  expect(data.room.windows.some((item: { width: number }) => item.width === 1.17)).toBe(true)
})

test('exporta e importa una copia con confirmación sin cambiar la escena', async ({ page }) => {
  await page.goto('/')
  await expandAllCatalogCategories(page)
  await expandCatalogCategory(page, 'Asientos')
  await page.getByRole('button', { name: 'Silla ＋ Añadir', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  const selector = page.getByRole('button', { name: 'Seleccionar diseño guardado' })
  await selector.click()
  await page.getByRole('button', { name: 'Más opciones de Diseño 1' }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('menuitem', { name: /Exportar diseño/ }).click()
  const download = await downloadPromise
  const content = await readFile((await download.path())!)
  await selector.click().catch(() => {})
  if (!(await page.getByRole('button', { name: /Importar diseño/ }).isVisible())) await selector.click()
  await page.locator('input[type=file]').setInputFiles({ name: 'habitacion.json', mimeType: 'application/json', buffer: content })
  const modal = page.getByRole('dialog', { name: 'Importar «Diseño 1»' })
  await expect(modal).toContainText('copia independiente')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('room-builder:v0.1:designs')!).length)).toBe(1)
  await modal.getByRole('button', { name: 'Confirmar importación' }).click()
  const data = await page.evaluate(() => JSON.parse(localStorage.getItem('room-builder:v0.1:designs')!))
  expect(data).toHaveLength(2)
  expect(data[0].id).not.toBe(data[1].id)
  expect(data[1].data.furniture[0].kind).toBe('chair')
})

test('una descarga 3D no se repite al borrar el diseño activo ni al cambiar de cámara', async ({ page }) => {
  await page.goto('/')
  await expandAllCatalogCategories(page)
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  const selector = page.getByRole('button', { name: 'Seleccionar diseño guardado' })
  await selector.click()
  await page.getByRole('button', { name: /Crear diseño/ }).click()
  await page.getByLabel('Nombre del diseño').fill('Segundo')
  await page.getByRole('button', { name: 'Crear en blanco' }).click()
  await selector.click({ button: 'right' })
  const downloads: string[] = []
  page.on('download', (download) => downloads.push(download.suggestedFilename()))
  const first = page.waitForEvent('download')
  await page.getByRole('menuitem', { name: /Descargar 3D/ }).click()
  await first
  await expect(page.locator('.toast')).toContainText('Modelo 3D descargado')
  await selector.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Borrar' }).click()
  const dialog = page.getByRole('dialog', { name: '¿Eliminar «Segundo»?' })
  await dialog.getByRole('button', { name: 'Eliminar diseño' }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: 'Libre', exact: true }).click()
  await page.waitForTimeout(1200)
  expect(downloads).toHaveLength(1)
})
