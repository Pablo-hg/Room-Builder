import { expect, test, type Locator, type Page } from '@playwright/test'

async function rename(page: Page, row: Locator, oldName: string, newName: string) {
  await row.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Renombrar' }).click()
  const input = page.getByRole('textbox', { name: `Nuevo nombre para ${oldName}` })
  await expect(input).toBeFocused()
  await input.fill(newName)
  await input.press('Enter')
}

test('edita el nombre en la fila y conserva el anterior si se deja vacío o se cancela', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Sillón.*Añadir/ }).click()
  const inspector = page.locator('.selection-section--inspector')
  const row = page.locator('.element-row').filter({ hasText: 'Sillón' })
  await expect(inspector.getByLabel('Nombre', { exact: true })).toHaveCount(0)
  await rename(page, row, 'Sillón', 'Lectura')
  await expect(inspector.getByRole('heading', { name: 'Lectura' })).toBeVisible()
  const renamed = page.locator('.element-row').filter({ hasText: 'Lectura' })
  await rename(page, renamed, 'Lectura', '   ')
  await expect(renamed).toBeVisible()
  await renamed.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Renombrar' }).click()
  const input = page.getByRole('textbox', { name: 'Nuevo nombre para Lectura' })
  await input.fill('Cancelado')
  await input.press('Escape')
  await expect(renamed).toBeVisible()
})

test('permite nombrar puerta y ventana en la lista y guarda sus nombres', async ({ page }) => {
  await page.goto('/')
  await rename(page, page.locator('.element-row').filter({ hasText: 'Puerta' }), 'Puerta', 'Entrada')
  await page.getByRole('button', { name: 'Ventana ＋ Añadir', exact: true }).click()
  const rows = page.locator('.element-row').filter({ hasText: 'Ventana' })
  await rename(page, rows.last(), 'Ventana 2', 'Ventanal')
  await expect(page.locator('.element-select').filter({ hasText: 'Ventanal' })).toBeVisible()
  await page.getByRole('button', { name: 'Guardar como' }).click()
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('room-builder:v0.1:designs') || '[]'))
  expect(stored[0].data.version).toBe(10)
  expect(stored[0].data.room.door.name).toBe('Entrada')
  expect(stored[0].data.room.windows.some((window: { name?: string }) => window.name === 'Ventanal')).toBe(true)
})

test('renombra superficies y carpetas en la escena sin campos de nombre en el inspector', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Pared.*Objeto independiente/ }).click()
  const inspector = page.locator('.selection-section--inspector')
  await expect(inspector.getByLabel('Nombre', { exact: true })).toHaveCount(0)
  const surface = page.locator('.element-row').filter({ hasText: 'Pared independiente' })
  await rename(page, surface, 'Pared independiente', 'Tabique')
  await expect(page.locator('.element-row').filter({ hasText: 'Tabique' })).toBeVisible()
  await page.getByRole('button', { name: 'Crear carpeta de elementos' }).click()
  const folder = page.locator('.element-folder').filter({ has: page.getByRole('button', { name: 'Carpeta Carpeta 1', exact: true }) }).last()
  await folder.getByRole('button', { name: 'Carpeta Carpeta 1', exact: true }).click()
  await expect(page.getByLabel('Nombre de la carpeta')).toHaveCount(0)
  await folder.locator('.element-folder__heading').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Renombrar' }).click()
  const input = page.getByLabel('Nuevo nombre para Carpeta 1')
  await input.fill('Muebles')
  await input.press('Enter')
  await expect(page.getByRole('button', { name: 'Carpeta Muebles', exact: true })).toBeVisible()
})

for (const view of ['Isométrica', 'Libre']) {
  test(`confirma el nombre al pulsar la escena en ${view}`, async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: view, exact: true }).click()
    await page.getByRole('button', { name: /Sillón.*Añadir/ }).click()
    await page.keyboard.press('F2')
    const input = page.getByRole('textbox', { name: 'Nuevo nombre para Sillón' })
    await input.fill('Rincón de lectura')
    const box = await page.locator('.scene-panel canvas').first().boundingBox()
    if (!box) throw new Error('Escena no disponible')
    await page.mouse.click(box.x + 15, box.y + 15)
    await expect(input).toHaveCount(0)
    await expect(page.locator('.element-select').filter({ hasText: 'Rincón de lectura' })).toBeVisible()
  })
}
