import { expect, test } from '@playwright/test'

test('dimensiones vinculadas a una carpeta completa y nombres locales de superficies', async ({ page }) => {
  await page.goto('/')
  const size = page.getByRole('textbox', { name: 'Introducir anchura en metros', exact: true })
  await expect(size).toBeDisabled()
  await page.getByRole('button', { name: 'Carpeta Raíz', exact: true }).click()
  await expect(size).toBeEnabled()
  const rootWidth = await size.inputValue()
  await page.getByRole('button', { name: /Nueva habitación vacía/ }).click()
  await page.getByRole('button', { name: 'Encima', exact: true }).click()
  const folder = page.locator('.element-folder').filter({ has: page.getByRole('button', { name: 'Carpeta Habitación 2', exact: true }) })
  await expect(folder.getByRole('button', { name: 'Suelo Superficie de construcción', exact: true })).toBeVisible()
  await expect(folder.getByRole('button', { name: /Habitación 2 · Suelo/ })).toHaveCount(0)
  await expect(size).toBeEnabled()
  await size.fill('7')
  await size.press('Enter')
  await expect(size).toHaveValue('7.00')
  await page.getByRole('button', { name: 'Carpeta Raíz', exact: true }).click()
  await expect(size).toHaveValue(rootWidth)
  await page.getByRole('button', { name: 'Carpeta Habitación 2', exact: true }).click()
  await expect(size).toHaveValue('7.00')
  await folder.getByRole('button', { name: 'Suelo Superficie de construcción', exact: true }).click()
  await expect(size).toBeDisabled()
})

test('añade puertas a otra habitación, selecciona en lista y deshace el borrado', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Nueva habitación vacía/ }).click()
  await page.getByRole('button', { name: 'Encima', exact: true }).click()
  await page.getByRole('button', { name: 'Puerta ＋ Añadir', exact: true }).click()
  const inspector = page.locator('.selection-section--inspector')
  await expect(inspector.getByRole('heading', { name: 'Puerta 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Puerta ＋ Añadir', exact: true }).click()
  await expect(inspector.getByRole('heading', { name: 'Puerta 2', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('puertas-en-pared.png') })
  await page.getByRole('button', { name: 'Plano', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('puertas-en-plano.png') })
  await inspector.getByRole('button', { name: 'Eliminar puerta', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Puerta 2 Apertura', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Deshacer el último cambio' }).click()
  await expect(page.getByRole('button', { name: 'Puerta 2 Apertura', exact: true })).toBeVisible()
})
