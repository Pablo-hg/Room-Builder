test('crea habitaciones en distintas caras y cambia de habitación en las vistas', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const create = async (direction: string) => {
    await page.getByRole('button', { name: /Nueva habitación vacía/ }).click()
    for (const wall of ['A', 'B', 'C', 'D']) await expect(page.getByRole('button', { name: `Pared ${wall}`, exact: true })).toBeVisible()
    await page.getByRole('button', { name: direction, exact: true }).click()
  }
  await create('Encima')
  await create('Pared B')
  await expect(page.getByRole('button', { name: /Piso 2 · Suelo Superficie de construcción/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /Piso 3 · Suelo Superficie de construcción/ })).toBeVisible()
  for (const view of ['Plano', 'Frontal', 'POV']) {
    await page.getByRole('button', { name: view, exact: true }).click()
    const selector = page.getByLabel('Habitación de la vista')
    await expect(selector.locator('option')).toHaveCount(3)
    if (view !== 'Plano') {
      await expect(selector.locator('optgroup')).toHaveCount(2)
      await expect(selector.locator('optgroup').nth(1).locator('option')).toHaveCount(2)
    } else await expect(selector.locator('optgroup')).toHaveCount(0)
    await selector.selectOption({ label: 'Habitación principal' })
    const canvas = page.locator('.scene-panel canvas').first()
    const base = await canvas.screenshot()
    await selector.selectOption({ index: 2 })
    const other = await canvas.screenshot()
    expect(base.equals(other)).toBe(false)
  }
})

test('la cámara isométrica se eleva y la libre responde a WASD', async ({ page }) => {
  const cameraEvents: string[] = []
  page.on('request', (request) => {
    if (request.url().includes('/__room-builder/interaction-log') && request.postData()?.includes('state.camera.orientation')) cameraEvents.push(request.postData()!)
  })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const canvas = page.locator('.scene-panel canvas').first()
  const before = await canvas.screenshot()
  await page.getByRole('slider', { name: 'Altura del centro de cámara isométrica' }).fill('2')
  expect(before.equals(await canvas.screenshot())).toBe(false)
  await page.getByRole('button', { name: 'Libre', exact: true }).click()
  await page.mouse.click(5, 5)
  const free = await canvas.screenshot()
  await page.keyboard.down('w')
  await page.waitForTimeout(300)
  await page.keyboard.up('w')
  expect(free.equals(await canvas.screenshot())).toBe(false)
  const beforeFast = await canvas.screenshot()
  await page.keyboard.down('Shift')
  await page.keyboard.down('w')
  await page.waitForTimeout(300)
  await page.keyboard.up('w')
  await page.keyboard.up('Shift')
  expect(beforeFast.equals(await canvas.screenshot())).toBe(false)
  const box = await canvas.boundingBox()
  if (!box) throw new Error('Canvas no disponible')
  const count = cameraEvents.length
  await page.mouse.move(box.x + box.width * 0.2, box.y + box.height * 0.25)
  await page.keyboard.down('w')
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.3, box.y + box.height * 0.3, { steps: 8 })
  await page.mouse.up()
  await page.keyboard.up('w')
  await expect.poll(() => cameraEvents.length, { timeout: 5000 }).toBeGreaterThan(count)
})
