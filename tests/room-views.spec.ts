import { expect, test } from '@playwright/test'

test('el selector isométrico centra la habitación y ajusta la altura', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: /Nueva habitación vacía/ }).click()
  await page.getByRole('button', { name: 'Encima', exact: true }).click()
  const selector = page.getByLabel('Habitación de la vista')
  const height = page.locator('.iso-height-control output')
  await expect(height).toHaveText('2.7 m')
  await selector.selectOption({ label: 'Habitación principal' })
  await expect(height).toHaveText('0.0 m')
  const canvas = page.locator('.scene-panel canvas').first()
  const base = await canvas.screenshot()
  await selector.selectOption({ label: 'Piso 2' })
  await expect(height).toHaveText('2.7 m')
  const upper = await canvas.screenshot()
  expect(base.equals(upper)).toBe(false)
  await page.getByRole('button', { name: /Nueva habitación vacía/ }).click()
  await page.getByRole('button', { name: 'Pared B', exact: true }).click()
  await selector.selectOption({ label: 'Piso 2' })
  const first = await canvas.screenshot()
  await selector.selectOption({ label: 'Piso 3' })
  expect(first.equals(await canvas.screenshot())).toBe(false)
  await expect(height).toHaveText('2.7 m')
})

