test('la flecha del eje X mueve la selección múltiple sin alterar el eje Z', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expandAllCatalogCategories(page)
  await expandCatalogCategories(page, ['Asientos', 'Mesas y auxiliares'])
  await page.getByRole('button', { name: 'Plano', exact: true }).click()
  await page.getByRole('button', { name: 'Sillón ＋ Añadir', exact: true }).click()
  await page.getByRole('button', { name: 'Mesa ＋ Añadir', exact: true }).click()
  await page.locator('.element-select').filter({ hasText: 'Sillón' }).click()
  await page.locator('.element-select').filter({ hasText: 'Mesa' }).click({ modifiers: ['Control'] })
  const xPosition = page.getByRole('slider', { name: /Posición X del conjunto/ })
  const zPosition = page.getByRole('slider', { name: /Posición Z del conjunto/ })
  const xBefore = Number(await xPosition.inputValue())
  const zBefore = Number(await zPosition.inputValue())
  const canvas = await page.locator('.scene-panel canvas').first().boundingBox()
  if (!canvas) throw new Error('Canvas no disponible')
  const zoom = Math.max(36, Math.min(canvas.width / 7.7, canvas.height / 6.7))
  const x = canvas.x + canvas.width / 2 + xBefore * zoom + 26
  const y = canvas.y + canvas.height / 2 + zBefore * zoom
  const canvasElement = page.locator('.scene-panel canvas').first()
  const normal = await canvasElement.screenshot()
  await page.mouse.move(x, y)
  const hovered = await canvasElement.screenshot()
  expect(hovered.equals(normal)).toBe(false)
  await page.mouse.down()
  await page.mouse.move(x + 45, y, { steps: 6 })
  await page.mouse.up()
  await expect(xPosition).not.toHaveValue(String(xBefore))
  await expect(zPosition).toHaveValue(String(zBefore))
})

