  const right = page.getByRole('separator', { name: 'Cambiar anchura del panel derecho' })
  const leftPanel = page.locator('#objects-panel')
  const rightPanel = page.locator('#settings-panel')
  const leftStart = (await leftPanel.boundingBox())!.width
  const rightStart = (await rightPanel.boundingBox())!.width
  const box = (await left.boundingBox())!
  await page.mouse.move(box.x + 5, box.y + 70)
  await page.mouse.down()
  await page.mouse.move(box.x + 205, box.y + 70, { steps: 5 })
  await page.mouse.up()
