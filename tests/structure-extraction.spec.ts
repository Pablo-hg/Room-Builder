import { expect, test } from '@playwright/test'

test('mueve un pack, redimensiona una superficie y deshace la edición', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Nueva habitación vacía/ }).click()
  await page.getByRole('button', { name: 'Encima', exact: true }).click()
  const inspector = page.locator('.selection-section--inspector')
  const packX = inspector.getByLabel('Mover pack X', { exact: true })
  const initialX = await packX.inputValue()
  await packX.focus()
  await packX.press('ArrowRight')
  await expect(packX).not.toHaveValue(initialX)
  await page.getByRole('button', { name: /Suelo · Editar/ }).click()
  const width = inspector.getByRole('slider', { name: 'Anchura', exact: true })
  const initialWidth = await width.inputValue()
  await width.focus()
  await width.press('ArrowRight')
  await expect(width).not.toHaveValue(initialWidth)
  await page.getByRole('button', { name: 'Deshacer el último cambio' }).click()
  await page.getByRole('button', { name: /Habitación 2 · Suelo Superficie de construcción/ }).click()
  await expect(width).toHaveValue(initialWidth)
  await page.getByRole('button', { name: 'Rehacer el último cambio deshecho' }).click()
  await page.getByRole('button', { name: /Habitación 2 · Suelo Superficie de construcción/ }).click()
  await expect(width).not.toHaveValue(initialWidth)
})

test('arrastra el gizmo de una superficie y deshace el gesto', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: /Nueva habitación vacía/ }).click()
  await page.getByRole('button', { name: 'Encima', exact: true }).click()
  await page.getByRole('button', { name: /Suelo · Editar/ }).click()
  await page.getByRole('button', { name: 'Plano', exact: true }).click()
  const bounds = await page.locator('.scene-panel canvas').first().boundingBox()
  if (!bounds) throw new Error('No se pudo localizar el canvas')
  const x = bounds.x + bounds.width * 0.5
  const y = bounds.y + bounds.height * 0.5
  const position = page.locator('.selection-section--inspector').getByLabel('Desplazamiento X', { exact: true })
  const initial = await position.inputValue()
  await page.mouse.move(x + 26, y)
  await page.mouse.down()
  await page.waitForTimeout(200)
  await page.mouse.move(x + 86, y, { steps: 8 })
  await page.mouse.up()
  await expect(position).not.toHaveValue(initial)
  await page.getByRole('button', { name: 'Deshacer el último cambio' }).click()
  await page.getByRole('button', { name: /Habitación 2 · Suelo Superficie de construcción/ }).click()
  await expect(position).toHaveValue(initial)
})
